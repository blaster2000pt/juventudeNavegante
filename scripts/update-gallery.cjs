const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const directory = path.join(root, "images", "galeria");
const files = fs.readdirSync(directory, { withFileTypes: true })
  .filter((entry) => entry.isFile() && /\.(jpe?g|png)$/i.test(entry.name))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, "pt", { numeric: true }));
const images = files.map((name) => ({
  src: `images/galeria/${encodeURIComponent(name)}`,
  alt: path.basename(name, path.extname(name)).replace(/[-_]+/g, " ").trim() ||
    "Fotografia da Juventude Navegante",
}));

fs.writeFileSync(
  path.join(root, "gallery-data.js"),
  "// Generated by node scripts/update-gallery.cjs. Do not edit manually.\n" +
    `window.JUNA_GALLERY_IMAGES = ${JSON.stringify(images, null, 2)};\n`,
  "utf8",
);
console.log(`Galeria atualizada: ${images.length} fotografia(s) em images/galeria.`);
